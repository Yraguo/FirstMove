CREATE TABLE IF NOT EXISTS users (
 id TEXT PRIMARY KEY, name TEXT NOT NULL UNIQUE COLLATE NOCASE, password TEXT NOT NULL,
 admin INTEGER NOT NULL DEFAULT 0, quota INTEGER, evening TEXT NOT NULL DEFAULT '20:00',
 disabled INTEGER NOT NULL DEFAULT 0
);
CREATE TABLE IF NOT EXISTS sessions (
 token TEXT PRIMARY KEY, uid TEXT NOT NULL REFERENCES users, expires INTEGER NOT NULL,
 enabled INTEGER NOT NULL DEFAULT 1
);
CREATE TABLE IF NOT EXISTS login_limits (name TEXT PRIMARY KEY, since INTEGER NOT NULL, misses INTEGER NOT NULL);
CREATE TABLE IF NOT EXISTS projects (
 id TEXT PRIMARY KEY, name TEXT NOT NULL, lead TEXT NOT NULL REFERENCES users,
 kind TEXT NOT NULL, priority INTEGER NOT NULL, color TEXT NOT NULL,
 start TEXT, end TEXT, archived INTEGER NOT NULL DEFAULT 0, trashed INTEGER
);
CREATE TABLE IF NOT EXISTS members (
 pid TEXT NOT NULL REFERENCES projects ON DELETE CASCADE, uid TEXT NOT NULL REFERENCES users,
 pinned INTEGER NOT NULL DEFAULT 0, hidden INTEGER NOT NULL DEFAULT 0, PRIMARY KEY(pid,uid)
);
CREATE TABLE IF NOT EXISTS invites (
 token TEXT PRIMARY KEY, pid TEXT REFERENCES projects ON DELETE CASCADE, expires INTEGER NOT NULL
);
CREATE TABLE IF NOT EXISTS records (
 id TEXT PRIMARY KEY, uid TEXT NOT NULL REFERENCES users, pid TEXT REFERENCES projects ON DELETE SET NULL,
 former TEXT, title TEXT NOT NULL DEFAULT '', body TEXT NOT NULL DEFAULT '', kind TEXT NOT NULL,
 shared INTEGER NOT NULL DEFAULT 0, pinned INTEGER NOT NULL DEFAULT 0, position INTEGER NOT NULL DEFAULT 0,
 version INTEGER NOT NULL DEFAULT 1, created INTEGER NOT NULL, updated INTEGER NOT NULL
);
CREATE TABLE IF NOT EXISTS revisions (
 rid TEXT NOT NULL REFERENCES records ON DELETE CASCADE, version INTEGER NOT NULL,
 body TEXT NOT NULL, PRIMARY KEY(rid,version)
);
CREATE TABLE IF NOT EXISTS conflicts (
 id TEXT PRIMARY KEY, rid TEXT NOT NULL REFERENCES records ON DELETE CASCADE, body TEXT NOT NULL, base INTEGER NOT NULL
);
CREATE TABLE IF NOT EXISTS tasks (
 id TEXT PRIMARY KEY, uid TEXT NOT NULL REFERENCES users, pid TEXT REFERENCES projects ON DELETE SET NULL,
 rid TEXT UNIQUE REFERENCES records ON DELETE SET NULL, assigned INTEGER NOT NULL DEFAULT 0,
 title TEXT NOT NULL, due TEXT, previous_due TEXT, priority INTEGER NOT NULL, prepare TEXT, handle TEXT,
 pin TEXT, status TEXT NOT NULL, done TEXT, reminder INTEGER NOT NULL DEFAULT 1,
 remind_minutes INTEGER, independent TEXT, created INTEGER NOT NULL
);
CREATE TABLE IF NOT EXISTS habits (
 id TEXT PRIMARY KEY, uid TEXT NOT NULL REFERENCES users, title TEXT NOT NULL,
 days TEXT NOT NULL, start TEXT NOT NULL, end TEXT
);
CREATE TABLE IF NOT EXISTS checks (
 hid TEXT NOT NULL REFERENCES habits ON DELETE CASCADE, day TEXT NOT NULL, PRIMARY KEY(hid,day)
);
CREATE TABLE IF NOT EXISTS assets (
 id TEXT PRIMARY KEY, uid TEXT NOT NULL REFERENCES users, name TEXT NOT NULL, size INTEGER NOT NULL,
 content BLOB NOT NULL
);
CREATE TABLE IF NOT EXISTS links (
 rid TEXT NOT NULL REFERENCES records ON DELETE CASCADE, aid TEXT NOT NULL REFERENCES assets ON DELETE CASCADE,
 PRIMARY KEY(rid,aid)
);
CREATE TRIGGER IF NOT EXISTS free_asset AFTER DELETE ON links BEGIN
 DELETE FROM assets WHERE id=OLD.aid AND NOT EXISTS (SELECT 1 FROM links WHERE aid=OLD.aid);
END;
CREATE INDEX IF NOT EXISTS member_user ON members(uid);
CREATE INDEX IF NOT EXISTS task_owner ON tasks(uid);
CREATE INDEX IF NOT EXISTS task_project ON tasks(pid);
CREATE INDEX IF NOT EXISTS record_project ON records(pid);
CREATE INDEX IF NOT EXISTS record_owner ON records(uid);
CREATE INDEX IF NOT EXISTS asset_links ON links(aid);
